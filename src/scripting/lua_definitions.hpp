inline std::string luaCompletion(std::string_view prefix) {
    std::string common;
    if (prefix.empty()) {
        return common;
    }
    bool first = true;
    for (const auto& definition : luaDefinitions) {
        const std::string_view name = definition.name;
        if (name.substr(0, prefix.size()) != prefix) {
            continue;
        }
        if (first) {
            common = name;
            first = false;
        } else {
            std::size_t n = 0;
            while (n < common.size() && n < name.size() && common[n] == name[n]) {
                ++n;
            }
            common.resize(n);
        }
    }
    return common;
}
